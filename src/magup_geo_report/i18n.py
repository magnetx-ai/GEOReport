def chrome(language: str) -> dict[str, str]:
    if language in _CHROME:
        return _CHROME[language]
    return _CHROME["en"]


def fmt(language: str, key: str, **kwargs: Any) -> str:
    bundle = chrome(language)
    template = bundle.get(key) or _CHROME["en"].get(key) or key
    if not kwargs:
        return template
    try:
        return template.format(**kwargs)
    except (KeyError, IndexError):
        return template


def localize_audit(audit: Any, language: str) -> Any:
    for check in getattr(audit, "checks", []) or []:
        check.title = fmt(language, f"check_{check.id}") or check.title
        check.detail = _localize_detail(language, getattr(check, "code", ""), getattr(check, "params", None), check.detail)
    for row in getattr(audit, "bot_rules", []) or []:
        row["detail"] = _localize_detail(language, row.get("code") or "", row.get("params"), row.get("detail") or "")
    return audit


def _localize_detail(language: str, code: str, params: dict[str, Any] | None, fallback: str) -> str:
    if not code:
        return fallback
    payload = dict(params or {})
    if "title" in payload:
        payload["title"] = fmt(language, "yes") if payload["title"] in (True, "yes", "true", "1") else fmt(language, "no")
    text = fmt(language, f"detail_{code}", **{key: "" if value is None else value for key, value in payload.items()})
    if text == f"detail_{code}":
        return fallback
    return text
